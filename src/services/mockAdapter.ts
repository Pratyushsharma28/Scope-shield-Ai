/**
 * ScopeShield AI — Mock Adapter for Local UI Development
 * 
 * STRICT ARCHITECTURAL BOUNDARY:
 * This mock adapter is exclusively for local frontend UI development and testing
 * when Member 2's backend server (http://localhost:3000/api/analyze) is offline.
 * 
 * Mock mode is kept completely separate from real API mode.
 * Output is ALWAYS labeled with `isDemoData: true` and includes explicit mock disclaimers.
 * It is NEVER presented as genuine AI analysis.
 */

import { AnalysisResult, ScopeClassification, SuggestedAction } from '../types';

export interface MockAdapterOptions {
  contractFile: File;
  clientRequest: string;
  estimatedExtraHours: number;
  hourlyRate: number;
  projectName?: string;
}

export const runMockAnalysis = async (
  options: MockAdapterOptions
): Promise<AnalysisResult> => {
  const { contractFile, clientRequest, estimatedExtraHours, hourlyRate, projectName } = options;

  // Simulate network & inference latency
  await new Promise((resolve) => setTimeout(resolve, 1400));

  const textLower = clientRequest.toLowerCase();
  const calculatedTotal = estimatedExtraHours * hourlyRate;

  let classification: ScopeClassification = 'OUT_OF_SCOPE';
  let confidenceScore = 95;
  let summary = `[MOCK ADAPTER] Evaluated against uploaded document "${contractFile.name}". The request introduces deliverables outside the baseline scope schedule.`;
  let suggestedAction: SuggestedAction = 'ISSUE_CHANGE_ORDER';

  if (textLower.includes('bug') || textLower.includes('fix') || textLower.includes('glitch') || textLower.includes('broken')) {
    classification = 'IN_SCOPE';
    confidenceScore = 92;
    summary = `[MOCK ADAPTER] Evaluated against uploaded document "${contractFile.name}". This request is classified as bug remediation covered under standard milestone quality assurance.`;
    suggestedAction = 'ACCEPT_AS_IS';
  } else if (textLower.includes('chart') || textLower.includes('tweak') || textLower.includes('minor') || textLower.includes('extra') || textLower.includes('color')) {
    classification = 'SCOPE_CREEP_RISK';
    confidenceScore = 86;
    summary = `[MOCK ADAPTER] Evaluated against uploaded document "${contractFile.name}". Ambiguous item detected. May cause sprint schedule slippage if not clarified.`;
    suggestedAction = 'REQUEST_CLARIFICATION';
  }

  const result: AnalysisResult = {
    id: `mock_anl_${Date.now()}`,
    contractId: `mock_cnt_${Date.now()}`,
    contractTitle: projectName || `Project (File: ${contractFile.name})`,
    clientName: 'Client Partner (Mock)',
    requestTitle: clientRequest.slice(0, 50) + (clientRequest.length > 50 ? '...' : ''),
    requestText: clientRequest,
    classification,
    confidenceScore,
    executiveSummary: `${summary}\n\n⚠️ NOTICE: Generated by Local Mock Adapter for UI development. No real AI inference was executed.`,
    detailedFindings: [
      `[MOCK DATA] Uploaded contract file: ${contractFile.name} (${(contractFile.size / 1024).toFixed(1)} KB, type: ${contractFile.type || 'text/plain'}).`,
      `[MOCK DATA] Submitted extra effort: ${estimatedExtraHours} hours @ ₹${hourlyRate.toLocaleString('en-IN')}/hr.`,
      `[MOCK DATA] Projected scope adjustment: ₹${calculatedTotal.toLocaleString('en-IN')}.`,
      classification === 'IN_SCOPE'
        ? '[MOCK DATA] Item appears consistent with sprint maintenance terms.'
        : '[MOCK DATA] Item exceeds standard boundaries and warrants a formal Change Order.',
    ],
    evidence: [
      {
        id: `mock_ev_${Date.now()}_1`,
        clauseTitle: 'Scope Boundary & Deliverables Schedule',
        sectionNumber: 'Section 1 (Mock Evidence)',
        contractSnippet: `Excerpts from "${contractFile.name}": Any work or feature addition exceeding the primary signed deliverables is subject to hourly billing at ₹${hourlyRate.toLocaleString('en-IN')}/hr.`,
        relevanceScore: 92,
        analysisNote: 'Generated by Local Mock Adapter based on uploaded file parameters.',
        isContradicting: classification !== 'IN_SCOPE',
      },
    ],
    costEstimate: {
      estimatedHoursMin: Math.max(1, Math.round(estimatedExtraHours * 0.8)),
      estimatedHoursMax: Math.round(estimatedExtraHours * 1.25),
      recommendedHourlyRate: hourlyRate,
      calculatedAmountMin: Math.round(estimatedExtraHours * 0.8 * hourlyRate),
      calculatedAmountMax: Math.round(estimatedExtraHours * 1.25 * hourlyRate),
      suggestedFixedPrice: calculatedTotal,
      timelineImpactDays: Math.ceil(estimatedExtraHours / 6),
      complexity: estimatedExtraHours > 30 ? 'HIGH' : estimatedExtraHours > 12 ? 'MEDIUM' : 'LOW',
    },
    suggestedAction,
    freelancerRecommendation: classification === 'IN_SCOPE'
      ? 'Acknowledge to client and resolve within the scheduled sprint.'
      : `Draft Change Order for ${estimatedExtraHours} hours (₹${calculatedTotal.toLocaleString('en-IN')}) before beginning work.`,
    status: classification === 'IN_SCOPE' ? 'IN_SCOPE_RESOLVED' : 'CHANGE_ORDER_ISSUED',
    isDemoData: true, // STRICTLY LABELED AS DEMO/MOCK
    analyzedAt: new Date().toISOString(),
    rawAiOutput: JSON.stringify(
      {
        mode: 'LOCAL_MOCK_ADAPTER',
        warning: 'This is mock data for local UI development only.',
        inputs: {
          fileName: contractFile.name,
          clientRequest,
          estimatedExtraHours,
          hourlyRate,
        },
      },
      null,
      2
    ),
  };

  return result;
};
